@patch("app.api.main.answer_question")
def test_valid_question(mock_answer_question):
    """
    A valid question should return a successful
    RAG response.

    The test verifies that the HTTP request ID
    generated by the middleware is propagated
    into the RAG service.
    """

    def mock_rag_response(
        question,
        request_id=None,
    ):
        return {
            "answer": (
                "The IPO offer price is ₦525.00."
            ),
            "sources": [
                {
                    "document": (
                        "dangote_refinery_valuation.pdf"
                    ),
                    "page": 1,
                    "chunk": 1,
                    "score": 0.525,
                }
            ],
            "request_id": request_id,
        }

    mock_answer_question.side_effect = (
        mock_rag_response
    )

    response = client.post(
        "/ask",
        headers=AUTH_HEADERS,
        json={
            "question": "What is the IPO offer price?"
        },
    )

    assert response.status_code == 200

    data = response.json()

    assert (
        data["answer"]
        == "The IPO offer price is ₦525.00."
    )

    assert len(data["sources"]) == 1

    assert (
        data["sources"][0]["document"]
        == "dangote_refinery_valuation.pdf"
    )

    # -----------------------------------------
    # Verify request-ID propagation
    # -----------------------------------------

    assert "x-request-id" in response.headers

    http_request_id = (
        response.headers["x-request-id"]
    )

    assert http_request_id

    assert data["request_id"] == http_request_id

    mock_answer_question.assert_called_once_with(
        "What is the IPO offer price?",
        request_id=http_request_id,
    )


