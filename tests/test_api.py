def test_ask_uses_financial_analysis_when_available(
    monkeypatch,
):
    financial_result = {
        "answer": "FINANCIAL ANALYSIS",
        "sources": [],
        "request_id": "financial-request",
        "analysis_type": "financial",
        "complete_history": True,
        "requested_period_count": 2,
        "available_period_count": 2,
        "missing_metrics": [],
    }

    def fake_financial(
        question,
        request_id=None,
    ):
        assert "revenue" in question.lower()
        assert request_id is not None
        return {
            **financial_result,
            "request_id": request_id,
        }

    def fail_rag(*args, **kwargs):
        raise AssertionError(
            "Ordinary RAG must not run when "
            "financial analysis succeeds."
        )

    monkeypatch.setattr(
        "app.api.main."
        "answer_financial_analysis_question",
        fake_financial,
    )

    monkeypatch.setattr(
        "app.api.main.answer_question",
        fail_rag,
    )

    response = client.post(
        "/ask",
        headers=AUTH_HEADERS,
        json={
            "question": (
                "Show ABC revenue for the "
                "last 2 years."
            )
        },
    )

    assert response.status_code == 200

    body = response.json()

    assert (
        body["answer"]
        == "FINANCIAL ANALYSIS"
    )

    assert (
        body["analysis_type"]
        == "financial"
    )

    assert body["request_id"]


def test_ask_falls_back_to_existing_rag(
    monkeypatch,
):
    calls = {
        "financial": 0,
        "rag": 0,
    }

    def fake_financial(
        question,
        request_id=None,
    ):
        calls["financial"] += 1
        return None

    def fake_rag(
        question,
        request_id=None,
    ):
        calls["rag"] += 1

        return {
            "answer": "ORDINARY RAG ANSWER",
            "sources": [],
            "request_id": request_id,
        }

    monkeypatch.setattr(
        "app.api.main."
        "answer_financial_analysis_question",
        fake_financial,
    )

    monkeypatch.setattr(
        "app.api.main.answer_question",
        fake_rag,
    )

    response = client.post(
        "/ask",
        headers=AUTH_HEADERS,
        json={
            "question": (
                "What is the IPO offer price?"
            )
        },
    )

    assert response.status_code == 200

    body = response.json()

    assert (
        body["answer"]
        == "ORDINARY RAG ANSWER"
    )

    assert calls == {
        "financial": 1,
        "rag": 1,
    }

    assert body["request_id"]


@patch("app.api.main.dispatch_document_ingestion")
def test_upload_accepts_tickerless_company(
    mock_dispatch_document_ingestion,
):
    """
    Private or unlisted issuers may not have a ticker or exchange.
    The upload API must preserve that valid issuer state rather
    than rejecting the document before ingestion.
    """

    mock_dispatch_document_ingestion.return_value = {
        "document_id": (
            "11111111-1111-1111-1111-111111111111"
        ),
        "document": "dangote-report.pdf",
        "status": "queued",
        "message_id": "message-111",
    }

    response = client.post(
        "/documents/upload",
        headers=AUTH_HEADERS,
        files={
            "file": (
                "dangote-report.pdf",
                b"%PDF-1.4 test",
                "application/pdf",
            ),
        },
        data={
            "company_name": (
                "Dangote Petroleum Refinery FZE"
            ),
            "country": "Nigeria",
            "currency": "NGN",
            "report_type": "annual",
            "fiscal_year": "2025",
            "period_end": "2025-12-31",
        },
    )

    assert response.status_code == 202

    kwargs = mock_dispatch_document_ingestion.call_args.kwargs

    assert kwargs["company_name"] == (
        "Dangote Petroleum Refinery FZE"
    )
    assert kwargs["ticker"] is None
    assert kwargs["exchange"] is None


