@patch("app.api.main.answer_question")
def test_rag_failure_returns_503(
    mock_answer_question,
):
    """
    A technical failure in the RAG pipeline should
    return HTTP 503 while preserving the HTTP
    correlation ID.
    """

    mock_answer_question.side_effect = RuntimeError(
        "Simulated RAG failure"
    )

    response = client.post(
        "/ask",
        headers=AUTH_HEADERS,
        json={
            "question": "What is the IPO offer price?"
        },
    )

    assert response.status_code == 503

    assert response.json() == {
        "detail": (
            "The AI service is temporarily "
            "unavailable."
        )
    }

    assert "x-request-id" in response.headers

    request_id = response.headers[
        "x-request-id"
    ]

    assert request_id

    mock_answer_question.assert_called_once_with(
        "What is the IPO offer price?",
        request_id=request_id,
    )

