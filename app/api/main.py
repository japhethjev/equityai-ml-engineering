# ---------------------------------------------------------
# HTTP observability middleware
# ---------------------------------------------------------

@app.middleware("http")
async def observe_http_request(
    request: Request,
    call_next,
):
    """
    Add a correlation ID to every HTTP request and record
    request-level latency and status.

    The request ID is stored on request.state so downstream
    application services can use the same correlation ID.
    """

    request_id = uuid.uuid4().hex[:12]

    request.state.request_id = request_id

    start = time.perf_counter()

    try:
        response = await call_next(request)

        duration_ms = round(
            (time.perf_counter() - start) * 1000,
            2,
        )

        response.headers["X-Request-ID"] = request_id

        logger.info(
            "event=http_request "
            "request_id=%s "
            "method=%s "
            "path=%s "
            "status=%s "
            "duration_ms=%s",
            request_id,
            request.method,
            request.url.path,
            response.status_code,
            duration_ms,
        )

        return response

    except Exception:
        duration_ms = round(
            (time.perf_counter() - start) * 1000,
            2,
        )

        logger.exception(
            "event=http_request_error "
            "request_id=%s "
            "method=%s "
            "path=%s "
            "duration_ms=%s",
            request_id,
            request.method,
            request.url.path,
            duration_ms,
        )

        raise


