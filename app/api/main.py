# ---------------------------------------------------------
# Delete document
# ---------------------------------------------------------

@app.delete(
    "/documents/{document_name}"
)
def remove_document(
    document_name: str,
):
    """
    Delete all vector chunks belonging to a document.
    """

    safe_document_name = Path(
        document_name
    ).name

    if not safe_document_name:
        raise HTTPException(
            status_code=400,
            detail="Document name is required.",
        )

    try:
        deleted_chunks = delete_document(
            safe_document_name
        )

        if deleted_chunks == 0:
            raise HTTPException(
                status_code=404,
                detail="Document not found.",
            )

        logger.info(
            "Deleted document=%s chunks=%s",
            safe_document_name,
            deleted_chunks,
        )

        return {
            "status": "success",
            "document": safe_document_name,
            "deleted_chunks": deleted_chunks,
        }

    except HTTPException:
        raise

    except Exception:
        logger.exception(
            "Failed to delete document: %s",
            safe_document_name,
        )

        raise HTTPException(
            status_code=503,
            detail=(
                "Document deletion temporarily "
                "unavailable."
            ),
        )