@app.get("/health")
def health():
    """
    Check API and database health.
    """

    try:
        with get_connection() as connection:
            with connection.cursor() as cursor:
                cursor.execute("SELECT 1;")
                cursor.fetchone()

        return {
            "status": "healthy",
            "api": "up",
            "database": "up",
        }

    except Exception:
        logger.exception(
            "Database health check failed"
        )

        raise HTTPException(
            status_code=503,
            detail="Database unavailable.",
        )


# ---------------------------------------------------------
# Ask endpoint
# ---------------------------------------------------------

@app.post("/ask")
def ask(
    payload: QuestionRequest,
    request: Request,
):
    """
    Answer a question using the EquityAI RAG pipeline.

    The HTTP request ID generated by the middleware is passed
    into the RAG service so one correlation ID traces the
    complete request.
    """

    question = payload.question.strip()

    if not question:
        raise HTTPException(
            status_code=400,
            detail="Question cannot be empty.",
        )

    request_id = request.state.request_id

    logger.info(
        "Received question request_id=%s",
        request_id,
    )

    try:
        result = answer_question(
            question,
            request_id=request_id,
        )

        logger.info(
            "Question answered successfully "
            "request_id=%s",
            request_id,
        )

        return result

    except Exception:
        logger.exception(
            "Failed to answer question "
            "request_id=%s",
            request_id,
        )

        raise HTTPException(
            status_code=503,
            detail=(
                "The AI service is temporarily "
                "unavailable."
            ),
        )


