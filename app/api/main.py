@app.post("/documents/upload")
def upload_document(
    file: UploadFile = File(...),
):
    """
    Upload and ingest a PDF document into the RAG system.
    """

    original_filename = Path(
        file.filename or ""
    ).name

    if not original_filename:
        raise HTTPException(
            status_code=400,
            detail="A filename is required.",
        )

    if (
        Path(original_filename).suffix.lower()
        != ".pdf"
    ):
        raise HTTPException(
            status_code=400,
            detail="Only PDF files are supported.",
        )

    temp_path = None

    try:
        with tempfile.NamedTemporaryFile(
            delete=False,
            suffix=".pdf",
        ) as temp_file:

            temp_path = Path(temp_file.name)

            shutil.copyfileobj(
                file.file,
                temp_file,
            )

        logger.info(
            "Starting document ingestion: %s",
            original_filename,
        )

        stats = ingest_document(
            str(temp_path),
            document_name=original_filename,
        )

        logger.info(
            "Document ingestion completed: "
            "document=%s "
            "total_chunks=%s "
            "new_chunks=%s "
            "existing_chunks=%s "
            "inserted=%s "
            "skipped=%s",
            original_filename,
            stats.get("total_chunks"),
            stats.get("new_chunks"),
            stats.get("existing_chunks"),
            stats.get("inserted"),
            stats.get("skipped"),
        )

        return {
            "status": "success",
            **stats,
        }

    except HTTPException:
        raise

    except Exception:
        logger.exception(
            "Document ingestion failed: %s",
            original_filename,
        )

        raise HTTPException(
            status_code=503,
            detail=(
                "Document ingestion temporarily "
                "unavailable."
            ),
        )

    finally:
        try:
            file.file.close()
        except Exception:
            pass

        if (
            temp_path is not None
            and temp_path.exists()
        ):
            try:
                temp_path.unlink()

            except OSError:
                logger.warning(
                    "Could not remove temporary file: %s",
                    temp_path,
                )


